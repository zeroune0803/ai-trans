def apply_translation():
    prs = Presentation(source_file)
    trans_map = load_dict()
    
    for slide in prs.slides:
        for shape in slide.shapes:
            if shape.has_text_frame:
                for paragraph in shape.text_frame.paragraphs:
                    # Get paragraph text
                    text = "".join(run.text for run in paragraph.runs).strip()
                    if text in trans_map:
                        translated_text = trans_map[text]
                        # Keep the formatting of the first run and clear others
                        # Then put to translated text into the first run
                        if len(paragraph.runs) > 0:
                            paragraph.runs[0].text = translated_text
                            for run in paragraph.runs[1:]:
                                run.text = ""

    prs.save(target_file)
    print(f"Translation mapped successfully. Saved to {target_file}")

